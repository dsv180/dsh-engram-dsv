/**
 * Пределы работы со словарём — общие для обеих половин плагина.
 *
 * Модуль намеренно без зависимостей: панель режет запросы на партии по `FILL_BATCH`,
 * сервер принимает партию и проверяет её по `FILL_REQUEST_MAX`, а сохранение правок
 * режется по размеру тела запроса (`splitDictionaryPatch`). Обе половины должны
 * называть одни и те же числа, а тянуть ради константы серверный модуль (с вызовом
 * модели) в клиентскую сборку нельзя — поэтому числа живут отдельно, как термины
 * словаря в `./dictionary-terms`.
 *
 * @module @kenz1117/dsh-engram/i18n/dictionary-limits
 */

/** Сколько терминов уходит в один запрос модели. */
export const FILL_BATCH = 40

/** Предел одной партии: больше принять нельзя — ответ не проверить на полноту. */
export const FILL_REQUEST_MAX = 120

/** Потолок вывода: строка перевода короче входа, но модель любит пояснять. */
export const FILL_MAX_TOKENS = 4096

/** Сколько ждём одну партию, прежде чем считать модель недоступной. */
export const FILL_TIMEOUT_MS = 120_000

/**
 * Сколько символов правок кладём в один запрос сохранения.
 *
 * Предел тела запроса на сервере — 64 КиБ (`readJsonBody`), а правок бывает больше
 * тысячи (набор сообщений при заполнении нового языка): одна пачка такого размера
 * не пролезет, и сохранение упёрлось бы в предел вместо записи. Берём меньше предела,
 * чтобы запас остался на JSON-обёртку и на длинные строки-исключения (в словаре
 * сообщений есть подсказки в несколько килобайт).
 */
export const SAVE_BYTES = 48 * 1024

/** Пара «английская строка → перевод»: тот же вид, что у правок из панели. */
export type DictionaryPatchRow = readonly [string, string]

/**
 * Разрезать правки на пачки, каждая из которых пролезает в тело запроса.
 *
 * Режется по длине самих строк, а не по их числу: в словаре рядом с короткими
 * подписями лежат многострочные подсказки, и «двести строк» — это то 20 КиБ, то
 * 200. Строка, которая одна больше предела, попадает в свою пачку: отказать в ней
 * хуже, чем отправить её одну (сервер по-прежнему решает, принимать ли её).
 * @param rows - правки в порядке таблицы.
 * @param limit - предел длины одной пачки в символах JSON.
 * @returns непустые пачки; пустой вход даёт пустой список.
 */
export function splitDictionaryPatch(
  rows: readonly DictionaryPatchRow[],
  limit: number = SAVE_BYTES,
): readonly (readonly DictionaryPatchRow[])[] {
  const chunks: DictionaryPatchRow[][] = []
  let current: DictionaryPatchRow[] = []
  let size = 0
  for (const row of rows) {
    const bytes = JSON.stringify(row).length + 1
    if (current.length > 0 && size + bytes > limit) {
      chunks.push(current)
      current = []
      size = 0
    }
    current.push(row)
    size += bytes
  }
  if (current.length > 0) chunks.push(current)
  return chunks
}
