/**
 * Причины, по которым ход диалога не был извлечён в память.
 *
 * Единый источник истины для обеих половин плагина: серверная возвращает их
 * в `IngestOutcome.skipped`, панель переводит их на язык пользователя (`SKIP_KEY`
 * в `src/client/EngramPanel.tsx`), а проверка `scripts/check-messages.mjs` сверяет,
 * что перевод есть для каждой причины.
 *
 * Русская доработка: список появился потому, что причина пропуска была известна
 * в момент решения, но никуда не сохранялась, а имена успели разойтись между
 * половинами плагина — панель ждала `unparsable`, конвейер возвращал
 * `unparseable-output`, и пользователь видел сырое английское значение вместо
 * перевода. Модуль намеренно **без зависимостей**: его импортируют и клиентская
 * половина, и проверки, поэтому серверный код сюда тянуть нельзя.
 */
export const INGEST_SKIP_REASONS = [
  /** Хода-предшественника нет (самый первый ход сессии). */
  'no-previous-turn',
  /** Запрошенного номера хода в журнале нет (повтор выкачки по ходу). */
  'no-such-turn',
  /** Этот ход уже извлекался: сработала защита от повторной записи. */
  'already-ingested',
  /** Дроссель: ход слишком мал по активности, чтобы тратить вызов модели. */
  'low-activity',
  /** Дроссель: сообщение целиком — светская беседа. */
  'chitchat',
  /** Дроссель: пользователь явно просил не запоминать. */
  'capture-forbidden',
  /** После очистки и обезличивания пользовательского текста не осталось. */
  'no-user-content',
  /** В журнале сессии нет запроса к модели, то есть маршрут не определить. */
  'no-route-in-log',
  /** Ответ вспомогательной модели не разобрался как массив JSON. */
  'unparseable-output',
  /**
   * Вызов прошёл, но памяти не прибавилось — и метки «нечего помнить» в ответе нет.
   *
   * Русская доработка (A-17): пустой результат неотличим от поломки возвращалки.
   * Осознанный отказ модели приходит предопределённым ответом `[{"nothing": true}]`
   * и отмечается отдельной операцией `ingest-nothing`; всё остальное, что дало ноль
   * записей (голый пустой массив, все кандидаты отсеялись), попадает сюда.
   */
  'empty-unmarked',
  /**
   * Извлечение началось и сорвалось уже после запроса к модели — ошибка вызова или записи.
   *
   * Русская доработка (A-17): раньше такой сбой жил только предупреждением в консоли
   * хоста — ни записи в памяти, ни строки в журнале, поэтому пропажу хода нельзя было
   * разобрать задним числом. Текст ошибки кладётся в detail.
   */
  'failed',
] as const

/** Одна из причин пропуска извлечения. */
export type IngestSkipReason = (typeof INGEST_SKIP_REASONS)[number]
